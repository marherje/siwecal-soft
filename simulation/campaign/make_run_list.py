#!/usr/bin/env python3
"""Run list of the run-by-run simulation (simulation/campaign/make_run_sim_dag.py): one line per data run,
    RUN set label E particle
with RUN the data folder name in Reconstruction/ (TB2026CERN_run_000022, TB2026CERN_eudaq_run_000291).

    python3 simulation/campaign/make_run_list.py [--points beam_points.txt] [--out runs_v10.txt]

Generated once from the runs column of beam_points.txt (each run with the set / label / energy of its point), then
maintained by hand: add or remove lines to change the campaign.
"""
import argparse
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def run_name(token):
    """beam_points.txt run token -> data folder name: 'e291' -> TB2026CERN_eudaq_run_000291, '22' -> ..._run_000022."""
    if token.startswith("e"):
        return f"TB2026CERN_eudaq_run_{int(token[1:]):06d}"
    return f"TB2026CERN_run_{int(token):06d}"


def read_runs(path):
    """[{run, set, label, E, particle}] in file order ('#' starts a comment)."""
    runs = []
    for line in open(path):
        f = line.split("#")[0].split()
        if len(f) >= 5:
            runs.append(dict(run=f[0], set=f[1], label=f[2], E=f[3], particle=f[4]))
    return runs


def main():
    from make_sim_dag import read_points   # same directory; imports siwecal_common

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--points", default=os.path.join(HERE, "beam_points.txt"))
    ap.add_argument("--out", default=os.path.join(HERE, "runs_v10.txt"))
    args = ap.parse_args()
    lines = [f"# Runs of the run-by-run simulation campaign final_v10 (simulation/campaign/make_run_sim_dag.py).",
             f"# Generated by make_run_list.py from {os.path.basename(args.points)} (runs column, set/label/E of their",
             "# point); edit by hand to change the campaign. RUN = data folder in Reconstruction/.",
             "#",
             f"# {'RUN':<30} {'set':<6} {'label':<6} {'E':<5} particle"]
    for p in read_points(args.points):
        for token in p["runs"].split(","):
            lines.append(f"{run_name(token):<32} {p['set']:<6} {p['label']:<6} {p['E']:<5} {p['particle'] or 'e-'}")
    open(args.out, "w").write("\n".join(lines) + "\n")
    print(f"{len(lines) - 5} runs -> {args.out}")


if __name__ == "__main__":
    main()
