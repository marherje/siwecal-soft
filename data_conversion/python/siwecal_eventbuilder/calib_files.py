"""
Calibration and geometry inputs of the Gaudi event builder (data_conversion/options/run_event_builder.py), resolved
the same way by every driver (data_conversion/jobs/condor/generate_reco_dag.py, run_full_pipeline_batch.py, the
calibration and diagnostics scripts): which MuonCalib tables a run is reconstructed with, its LG->HG anchor line,
and the per-slab pad maps.

What is left of the former Python event builder of siwecal-tb2026 (cli.py, pipeline, hit collector, ...), which
duplicated EcalEventBuilder and is retired: the event building is Gaudi's only.
"""
import glob
import os
import sys

from siwecal_common import paths

from .geometry import load_slab_technology

# The official Gaudi tables (re-derived on the fixed-SCA-pairing chunks), on EOS: <calib_dir>/MuonCalib.
GAUDI_CALIB_DIR = paths.muon_calib_dir()

# Per-slab z positions for hit_z, and (technology block) which slab needs a pad map of its own (slab 12, the FEV11
# chip-on-board).
SLAB_Z_FILE_DEFAULT = paths.geometry_file("slab_z_positions.yml")


def _default_pad_map_files() -> dict:
    """``{"default": file, slab: file}`` (basenames, resolved later against the
    mappings directory) from the slab file's technology block; the all-FEV10
    fallback when the file does not exist."""
    if os.path.isfile(SLAB_Z_FILE_DEFAULT):
        files = load_slab_technology(SLAB_Z_FILE_DEFAULT).pad_map_files()
        return {k: os.path.basename(v) for k, v in files.items()}
    return {"default": "fev10_rotate_chip_channel_x_y_mapping.txt"}


PAD_MAP_FILES_DEFAULT = _default_pad_map_files()

# Default calibration of the reconstruction drivers (generate_reco_dag.py,
# run_full_pipeline_batch.py): the final campaign's, so a new reconstruction matches
# what is in Reconstruction/ without remembering flags (user decision 2026-10-13).
#   * pedestals (and so the pedestal mask) and MIPs of th210 for EVERY run: the th210
#     muon calibration is the only one fitted with the discriminator below the MIP peak
#     (th230 fits only 3452 channels);
#   * the LG->HG anchor line of the run's OWN period (read_gain_anchor), a property of
#     the data taking, not of the pedestal table.
# Pass "own" to --ped-th / --mip-th for the run's own threshold instead.
# resolve_gaudi_calib_files itself still defaults to the run's own threshold.
PED_CALIB_TH = "210"
MIP_CALIB_TH = "210"


def calib_th_arg(value):
    """--ped-th / --mip-th value: "own" (or "") -> None (the run's own threshold), else the threshold."""
    return None if value in (None, "", "own") else str(value)


def read_gain_anchor(calib_dir, th):
    """(k, c) of <calib_dir>/anchor/th<th>/gain_anchor_th<th>.txt, or ("-", "-") if absent (the event-builder
    steering then keeps its built-in GainRatio/GainIntercept 0.0962/1.45)."""
    if not calib_dir:
        return ("-", "-")
    path = os.path.join(calib_dir, "anchor", f"th{th}", f"gain_anchor_th{th}.txt")
    if not os.path.exists(path):
        print(f"[anchor] no {path}: steering default GainRatio/GainIntercept")
        return ("-", "-")
    vals = {}
    for line in open(path):
        parts = line.split()
        if len(parts) >= 2 and not line.startswith("#"):
            vals[parts[0]] = parts[1]
    return (vals["k"], vals["c"])


def resolve_gaudi_calib_files(th, mip_th=None, ped_th=None, calib_dir=None):
    """Return (ped_hg, mip_hg, ped_lg, mip_lg) from ``MuonCalib`` (``GAUDI_CALIB_DIR``).

    Same role as :func:`resolve_muon_calib_files`, but for the tables generated by
    the Gaudi ``PedestalMipCalibrator`` -- which are named after the calibration
    run they came from (``*_run_000004_highgain.txt``), not after the threshold,
    so the files are globbed rather than spelled out.

    THE PEDESTAL AND THE MIP BOTH COME FROM ``th`` by default (``mip_th is None``).
    Each pipeline auto-calibrates from its own threshold: both the pedestal and the
    MIP MPV genuinely shift with the trigger threshold, so borrowing another
    threshold's MIP does not hold up. ``mip_th`` still exists as an explicit override
    for deliberate cross-threshold studies, but it is no longer defaulted to th220.

    Why per-threshold, for both quantities:

    * The MIP MPV, in ADC, is NOT the same across thresholds. It has to be fit
      separately for each: the MIP histogram is only filled when the channel FIRES,
      so the discriminator cuts the spectrum from the left, and where that cut lands
      relative to the peak differs by threshold. Assuming one ADC MIP value serves
      every threshold is wrong -- so each threshold gets its own MIP table, produced
      by a fit that accounts for its own trigger cut.

    * The PEDESTAL is measured from the samples that did NOT fire, and it drifts
      between runs (the th220 and th230 tables differ by a median 1.27 ADC in the
      high gain, RMS 3.3; 68% of channel-SCAs by more than 1 ADC). Forcing one
      threshold's pedestals onto another injects an error that does not exist, so
      each threshold keeps its own.

    A missing ``th{th}`` folder, or one holding no high-gain table, is a hard error:
    silently falling back to another threshold's tables is exactly how a run ends up
    reconstructed against the wrong pedestals.

    ``ped_th`` is the pedestal counterpart of ``mip_th``: an explicit override for a
    study that puts every run on ONE calibration (pedestals, pedestal mask and MIP
    of the same threshold, e.g. th210 for all). Not the default, for the reason above.

    The LOW-gain pair is optional and comes back as ``("", "")`` when absent --
    the event builder then keeps taking every hit's energy from the high gain,
    instead of the threshold becoming unusable. They are returned as a pair or
    not at all: half a low-gain calibration is worse than none.

    ``calib_dir`` replaces ``MuonCalib`` by another folder with the same
    ``{pedestals,mips}/th<N>/`` layout (e.g. a test tree produced by run_calibration_batch.py
    of the repo, from before the SCA column-order fix). Default: ``GAUDI_CALIB_DIR``.
    """
    base = GAUDI_CALIB_DIR if calib_dir is None else calib_dir
    mip_th = str(th) if mip_th is None else str(mip_th)
    ped_th = str(th) if ped_th is None else str(ped_th)

    def _one(kind, pattern, required, folder_th):
        folder = os.path.join(base, kind, f"th{folder_th}")
        if not os.path.isdir(folder):
            if not required:
                return ""
            print(f"ERROR: calibration folder not available for threshold {folder_th}: {folder}",
                  file=sys.stderr)
            sys.exit(1)
        # Run numbers are zero-padded, so lexicographic sort = numeric order.
        candidates = sorted(glob.glob(os.path.join(folder, pattern)))
        if not candidates:
            if not required:
                return ""
            print(f"ERROR: calibration folder for threshold {folder_th} holds no {kind} "
                  f"table matching {pattern}: {folder}", file=sys.stderr)
            sys.exit(1)
        return candidates[-1]

    ped_hg = _one("pedestals", "Pedestal_*_highgain.txt", True, ped_th)
    mip_hg = _one("mips", "MIP_pedestalsubmode1_*_highgain.txt", True, mip_th)
    ped_lg = _one("pedestals", "Pedestal_*_lowgain.txt", False, ped_th)
    mip_lg = _one("mips", "MIP_pedestalsubmode1_*_lowgain.txt", False, mip_th)
    if not (ped_lg and mip_lg):
        ped_lg = mip_lg = ""
    if str(ped_th) != str(th):
        print(f"[calib] threshold {th}: pedestals from th{ped_th}")
    if str(mip_th) != str(th):
        print(f"[calib] threshold {th}: MIP from th{mip_th}")
    return ped_hg, mip_hg, ped_lg, mip_lg
